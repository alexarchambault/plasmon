package plasmon.bsp

class MillWrappedSourcesTests extends munit.FunSuite {

  private val original = os.root / "project" / "build.mill"

  // What Mill 1.3.1 generates out of a build.mill (out/mill-build/generatedScriptSources.dest/wrapped)
  private val topWrapper =
    s"""// Generated by Mill SNAPSHOT
       |package build_
       |
       |import build_.{package_ => build}
       |
       |object package_ extends package_ {
       |  override lazy val millDiscover: _root_.mill.api.Discover = _root_.mill.api.Discover[this.type]
       |}
       |
       |abstract class package_
       |    extends _root_.mill.util.MainRootModule { this: package_.type =>
       |
       |///SOURCE_CODE_START:$original
       |""".stripMargin
  private val bottomWrapper = "}"

  private val tq = "\"\"\""

  private def generated(userCode: String): String =
    topWrapper + userCode + bottomWrapper

  private def wrappers(generatedContent: String, originalContent: String) =
    MillWrappedSources.wrappers(
      generatedContent,
      p => if (p == original) Some(originalContent) else None
    )

  test("user code copied as is") {
    val code =
      """import mill.*
        |
        |object a extends mill.scalalib.ScalaModule {
        |  def moduleDeps = Seq(build.b)
        |}
        |""".stripMargin
    assertEquals(
      wrappers(generated(code), code),
      Some((original, topWrapper, bottomWrapper))
    )
  }

  test("margins stripped from the user code") {
    val code =
      s"""def org0 = "foo"
         |
         |def script = s${tq}foo bar
         |                |set -e
         |                |echo $${org0}
         |                |$tq.stripMargin
         |
         |object a extends mill.scalalib.ScalaModule {
         |  def moduleDeps = Seq(build.b)
         |}
         |""".stripMargin
    // Mill passes the whole generated file, user code included, to stripMargin
    val generatedCode = code.stripMargin
    assert(generatedCode.length < code.length)
    assertEquals(
      wrappers(generated(generatedCode), code),
      Some((original, topWrapper, bottomWrapper))
    )
  }

  test("margin stripped from the last user line, without line break") {
    val code =
      s"""def script = ${tq}a
         |  |b$tq.stripMargin""".stripMargin
    assertEquals(
      wrappers(topWrapper + code.stripMargin + "\n}", code),
      Some((original, topWrapper, "\n}"))
    )
  }

  test("bottom wrapper spanning several lines") {
    val code   = "def a = 2\n"
    val bottom = "\n}\n\nexport build_._\n"
    assertEquals(
      wrappers(topWrapper + code + bottom, code),
      Some((original, topWrapper, bottom))
    )
  }

  test("more lines in the original than in the generated source") {
    val code = "def a = 2\ndef b = 3\n"
    assertEquals(wrappers(topWrapper + "def a = 2\n", code), None)
  }

  test("unknown original") {
    assertEquals(
      MillWrappedSources.wrappers(generated("def a = 2\n"), _ => None),
      None
    )
  }
}
